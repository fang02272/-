def expand_keywords(keyword_map):
    """
    利用 TERM_ALIAS_MAP 为关键词词典自动生成同义词条目。
    新条目继承原词的分类映射，大幅提升匹配覆盖度而不需要手动逐条添加。
    同时确保规范术语本身也注册到词库中。
    """
    expanded = dict(keyword_map)
    # 第一遍：已有词 → 展开其全部同义词
    for canonical_term, category in keyword_map.items():
        for alias_term, synonyms in TERM_ALIAS_MAP.items():
            if canonical_term == alias_term or canonical_term in synonyms:
                for syn in synonyms:
                    if syn not in expanded:
                        expanded[syn] = category
    # 第二遍：规范词补录 — 若规范词本身不在词库，通过别名反查类别
    for canonical, aliases in TERM_ALIAS_MAP.items():
        if canonical not in expanded:
            for alias in aliases:
                if alias in expanded:
                    expanded[canonical] = expanded[alias]
                    break
    return expanded

